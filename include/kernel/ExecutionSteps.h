#ifndef EXECUTION_STEPS_H
#define EXECUTION_STEPS_H


enum ExecutionStep
{

    STEP_IDLE = 0,


    // Sensor
    STEP_SENSOR_READ,

    STEP_SENSOR_PROCESS,

    STEP_SENSOR_BUFFER,


    // Communication

    STEP_COMMUNICATION_CREATE,

    STEP_COMMUNICATION_PREPARE,

    STEP_COMMUNICATION_SEND,

    STEP_COMMUNICATION_WAIT_ACK,

    STEP_COMMUNICATION_CONFIRM,


    // Generic finish
    STEP_COMPLETE

};


#endif